const fs = require('fs');
const path = require('path');

const rootDir = path.resolve(__dirname, '..');
const envPath = path.join(rootDir, '.env');
const envLocalPath = path.join(rootDir, '.env.local');
const packageJsonPath = path.join(rootDir, 'package.json');
const packageLockPath = path.join(rootDir, 'package-lock.json');
const versionTsPath = path.join(rootDir, 'src', 'version.ts');

function parseEnv(filePath) {
    if (!fs.existsSync(filePath)) return {};
    const content = fs.readFileSync(filePath, 'utf8');
    const result = {};
    const lines = content.split(/\r?\n/);
    for (const line of lines) {
        const trimmed = line.trim();
        if (!trimmed || trimmed.startsWith('#')) continue;
        const match = trimmed.match(/^([A-Za-z_0-9]+)\s*=\s*(.*)$/);
        if (match) {
            let val = match[2].trim();
            if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
                val = val.slice(1, -1);
            }
            result[match[1]] = val;
        }
    }
    return result;
}

// 1. Parse .env and .env.local
const envVars = {
    ...parseEnv(envPath),
    ...parseEnv(envLocalPath),
};

// 2. Read package.json
if (!fs.existsSync(packageJsonPath)) {
    console.error('[sync-version] ERROR: package.json not found!');
    process.exit(1);
}

const pkgRaw = fs.readFileSync(packageJsonPath, 'utf8');
const pkg = JSON.parse(pkgRaw);

let version = (envVars.VERSION || pkg.version || '1.0.0').trim();
let buildTag = (envVars.BUILD_TAG || 'b62').trim();

// Clean version string (remove leading 'v' if present)
if (version.startsWith('v') || version.startsWith('V')) {
    version = version.slice(1);
}

// Semver validation
const semverRegex = /^[0-9]+\.[0-9]+\.[0-9]+(-[0-9A-Za-z.-]+)?(\+[0-9A-Za-z.-]+)?$/;
if (!semverRegex.test(version)) {
    console.error(`[sync-version] ERROR: Invalid semver format in .env: "${version}". Expected format: X.Y.Z (e.g. 3.2.3)`);
    process.exit(1);
}

// 3. Update package.json if version changed
let pkgUpdated = false;
if (pkg.version !== version) {
    pkg.version = version;
    fs.writeFileSync(packageJsonPath, JSON.stringify(pkg, null, 2) + '\n', 'utf8');
    pkgUpdated = true;
}

// 4. Update package-lock.json if exists
if (fs.existsSync(packageLockPath)) {
    try {
        const lockRaw = fs.readFileSync(packageLockPath, 'utf8');
        const lock = JSON.parse(lockRaw);
        let lockUpdated = false;
        if (lock.version !== version) {
            lock.version = version;
            lockUpdated = true;
        }
        if (lock.packages && lock.packages[''] && lock.packages[''].version !== version) {
            lock.packages[''].version = version;
            lockUpdated = true;
        }
        if (lockUpdated) {
            fs.writeFileSync(packageLockPath, JSON.stringify(lock, null, 2) + '\n', 'utf8');
        }
    } catch (err) {
        console.warn('[sync-version] Warning: Failed to update package-lock.json:', err.message);
    }
}

// 5. Generate src/version.ts
const versionTsContent = `// Auto-generated by scripts/sync-version.js. Do not edit manually.
// Source: .env or package.json
export const EXTENSION_VERSION = '${version}';
export const BUILD_TAG = '${buildTag}';
`;

fs.writeFileSync(versionTsPath, versionTsContent, 'utf8');

const sourceLabel = envVars.VERSION ? '.env' : 'package.json';
console.log(`[sync-version] Synced version from ${sourceLabel}: v${version} (${buildTag})${pkgUpdated ? ' -> package.json updated' : ''}`);
